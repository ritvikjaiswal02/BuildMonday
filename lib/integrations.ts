import type { Issue, IssueStatus, PrdStub } from "./types";

const KEY = "buildmonday:integrations";

export interface IntegrationsConfig {
  github?: { owner: string; repo: string };
  linear?: { workspace: string };
}

export function loadIntegrations(): IntegrationsConfig {
  if (typeof window === "undefined") return {};
  try {
    const raw = window.localStorage.getItem(KEY);
    return raw ? (JSON.parse(raw) as IntegrationsConfig) : {};
  } catch {
    return {};
  }
}

export function saveIntegrations(cfg: IntegrationsConfig) {
  if (typeof window === "undefined") return;
  try {
    window.localStorage.setItem(KEY, JSON.stringify(cfg));
  } catch {
    // ignore
  }
}

const ACTION_LABEL: Record<Issue["recommended_action"], string> = {
  fix_now: "Fix Now",
  investigate: "Investigate",
  monitor: "Monitor",
};

const STATUS_LABEL: Record<IssueStatus | "ignored", string> = {
  backlog: "Backlog",
  in_progress: "In Progress",
  shipped: "Shipped",
  ignored: "Ignored",
};

/**
 * Makes untrusted text (review quotes, and model output derived from them)
 * safe to drop into a GitHub or Linear issue body: one line, no mentions that
 * would ping people (@user, @org/team), no links, images, HTML or code spans.
 */
export function sanitizeTrackerText(value: string | null | undefined, max = 500): string {
  return (value ?? "")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, max)
    .replace(/@/g, "@\u200b")
    .replace(/([\\`*_[\]<>|#!])/g, "\\$1");
}

const bullets = (arr: string[]) => arr.map((x) => `- ${sanitizeTrackerText(x)}`).join("\n");

export function buildIssueMarkdown(
  issue: Issue,
  prd: PrdStub | null,
  status: IssueStatus | "ignored" = "backlog",
  opts?: { link?: string | null }
): { title: string; body: string } {
  const title = `[BuildMonday] ${issue.title.replace(/\s+/g, " ").replace(/@/g, "@\u200b").trim()}`;

  const evidence = issue.evidence
    .slice(0, 3)
    .map((e) => `> ${sanitizeTrackerText(e)}`)
    .join("\n>\n");

  const prdBlock = prd
    ? `

## PRD Stub

**Problem Statement:** ${sanitizeTrackerText(prd.problem_statement, 2000)}

**Affected Users:**
${bullets(prd.affected_users)}

**Acceptance Criteria:**
${bullets(prd.acceptance_criteria)}

**Edge Cases:**
${bullets(prd.edge_cases)}

**Success Metrics:**
${bullets(prd.success_metrics)}

**Implementation Notes:** ${sanitizeTrackerText(prd.implementation_notes, 2000)}

**Estimated Complexity:** ${prd.estimated_complexity}`
    : "";

  const body = `**Priority:** ${ACTION_LABEL[issue.recommended_action]} | **Severity:** ${issue.severity} | **Churn Risk:** ${issue.churn_risk} | **Effort:** ${issue.effort} | **Status:** ${STATUS_LABEL[status]}
**Affected:** ${sanitizeTrackerText(issue.affected_segment)}
**Frequency:** ${issue.frequency} complaint${issue.frequency === 1 ? "" : "s"}

## Why this ranks here
${issue.ranking_reason ? sanitizeTrackerText(issue.ranking_reason, 1000) : "_Not provided._"}

## Evidence
${evidence}${prdBlock}

---
${opts?.link ? `[View this issue in BuildMonday](${opts.link})

` : ""}_Generated by BuildMonday from customer complaints._`;

  return { title, body };
}

export function parseGithubRepo(
  rawOwner: string,
  rawRepo: string
): { owner: string; repo: string } | null {
  const combined = `${rawOwner} ${rawRepo}`;
  const urlMatch = combined.match(
    /github\.com[/:]([A-Za-z0-9._-]+)\/([A-Za-z0-9._-]+?)(?:\.git)?(?:[/?#\s]|$)/i
  );
  if (urlMatch) {
    return { owner: urlMatch[1], repo: urlMatch[2] };
  }
  for (const candidate of [rawOwner.trim(), rawRepo.trim()]) {
    const slashMatch = candidate.match(
      /^([A-Za-z0-9._-]+)\/([A-Za-z0-9._-]+?)(?:\.git)?\/?$/
    );
    if (slashMatch) {
      return { owner: slashMatch[1], repo: slashMatch[2] };
    }
  }
  const o = rawOwner.trim().replace(/\/$/, "");
  const r = rawRepo.trim().replace(/\/$/, "").replace(/\.git$/i, "");
  if (o && r && /^[A-Za-z0-9._-]+$/.test(o) && /^[A-Za-z0-9._-]+$/.test(r)) {
    return { owner: o, repo: r };
  }
  return null;
}

export function parseLinearWorkspace(raw: string): string | null {
  const trimmed = raw.trim().replace(/^@/, "");
  if (!trimmed) return null;
  const urlMatch = trimmed.match(/linear\.app\/([A-Za-z0-9_-]+)/i);
  if (urlMatch) return urlMatch[1].toLowerCase();
  if (/^[A-Za-z0-9_-]+$/.test(trimmed)) return trimmed.toLowerCase();
  return null;
}

export function buildLinearWorkspaceUrl(workspace: string): string {
  return `https://linear.app/${encodeURIComponent(workspace)}`;
}

const GITHUB_BODY_LIMIT = 6000;

export function buildGitHubIssueUrl(
  owner: string,
  repo: string,
  title: string,
  body: string
): string {
  const safeOwner = encodeURIComponent(owner.trim());
  const safeRepo = encodeURIComponent(repo.trim());
  const truncated =
    body.length > GITHUB_BODY_LIMIT
      ? body.slice(0, GITHUB_BODY_LIMIT) +
        "\n\n_…truncated. Full PRD on the original BuildMonday session._"
      : body;
  const params = new URLSearchParams({ title, body: truncated });
  return `https://github.com/${safeOwner}/${safeRepo}/issues/new?${params.toString()}`;
}

// ---------------------------------------------------------------------------
// Tracker API clients. Pure fetch, client-safe: secrets are passed in by the
// caller (the server decrypts them; nothing here reads the environment).
// Every function throws an Error with a user-facing message on failure.
// ---------------------------------------------------------------------------

const LINEAR_API = "https://api.linear.app/graphql";
const GITHUB_API = "https://api.github.com";
const TRACKER_TIMEOUT_MS = 15_000;

function trackerSignal(): AbortSignal | undefined {
  return typeof AbortSignal !== "undefined" && "timeout" in AbortSignal
    ? AbortSignal.timeout(TRACKER_TIMEOUT_MS)
    : undefined;
}

const LINEAR_BAD_KEY = "Linear did not accept this API key. Create a personal API key in Linear under Settings, API.";

async function linearRequest<T>(apiKey: string, query: string, variables: Record<string, unknown>): Promise<T> {
  let res: Response;
  try {
    res = await fetch(LINEAR_API, {
      method: "POST",
      headers: { "Content-Type": "application/json", Authorization: apiKey.trim() },
      body: JSON.stringify({ query, variables }),
      signal: trackerSignal(),
    });
  } catch {
    throw new Error("Could not reach Linear. Try again in a moment.");
  }
  let payload: {
    data?: T;
    errors?: Array<{ message?: string; extensions?: { userPresentableMessage?: string } }>;
  } = {};
  try {
    payload = (await res.json()) as typeof payload;
  } catch {
    // handled below
  }
  if (res.status === 401 || res.status === 403) throw new Error(LINEAR_BAD_KEY);
  if (!res.ok || payload.errors?.length) {
    const first = payload.errors?.[0];
    const detail = first?.extensions?.userPresentableMessage ?? first?.message;
    if (detail && /authenticat|api key/i.test(detail)) throw new Error(LINEAR_BAD_KEY);
    throw new Error(detail ? `Linear returned an error: ${detail}` : `Linear returned ${res.status}.`);
  }
  if (!payload.data) throw new Error("Linear returned an empty response.");
  return payload.data;
}

/** Teams the API key can see, sorted by name. */
export async function listLinearTeams(apiKey: string): Promise<Array<{ id: string; name: string; key: string }>> {
  const data = await linearRequest<{ teams: { nodes: Array<{ id: string; name: string; key: string }> } }>(
    apiKey,
    "query Teams { teams(first: 100) { nodes { id name key } } }",
    {},
  );
  return [...data.teams.nodes].sort((a, b) => a.name.localeCompare(b.name));
}

async function findLinearLabelId(apiKey: string, teamId: string, labelName: string): Promise<string | null> {
  const data = await linearRequest<{
    team: { labels: { nodes: Array<{ id: string; name: string }> } } | null;
    issueLabels: { nodes: Array<{ id: string; name: string }> };
  }>(
    apiKey,
    `query Labels($teamId: String!) {
      team(id: $teamId) { labels(first: 250) { nodes { id name } } }
      issueLabels(first: 250) { nodes { id name } }
    }`,
    { teamId },
  );
  const wanted = labelName.trim().toLowerCase();
  const all = [...(data.team?.labels.nodes ?? []), ...data.issueLabels.nodes];
  return all.find((l) => l.name.trim().toLowerCase() === wanted)?.id ?? null;
}

export async function createLinearIssue(args: {
  apiKey: string;
  teamId: string;
  title: string;
  description: string;
  labelName?: string | null;
}): Promise<{ id: string; identifier: string; url: string }> {
  let labelIds: string[] | undefined;
  if (args.labelName?.trim()) {
    try {
      const id = await findLinearLabelId(args.apiKey, args.teamId, args.labelName);
      if (id) labelIds = [id];
    } catch {
      // A missing label never blocks filing the issue.
      labelIds = undefined;
    }
  }
  const data = await linearRequest<{
    issueCreate: { success: boolean; issue: { id: string; identifier: string; url: string } | null };
  }>(
    args.apiKey,
    `mutation CreateIssue($input: IssueCreateInput!) {
      issueCreate(input: $input) { success issue { id identifier url } }
    }`,
    {
      input: {
        teamId: args.teamId,
        title: args.title.slice(0, 250),
        description: args.description,
        ...(labelIds ? { labelIds } : {}),
      },
    },
  );
  if (!data.issueCreate.success || !data.issueCreate.issue) {
    throw new Error("Linear did not create the issue. Check the team still exists.");
  }
  return data.issueCreate.issue;
}

async function githubRequest<T>(token: string, path: string, init?: { method?: string; body?: unknown }): Promise<T> {
  let res: Response;
  try {
    res = await fetch(`${GITHUB_API}${path}`, {
      method: init?.method ?? "GET",
      headers: {
        Accept: "application/vnd.github+json",
        Authorization: `Bearer ${token.trim()}`,
        "X-GitHub-Api-Version": "2022-11-28",
        ...(init?.body !== undefined ? { "Content-Type": "application/json" } : {}),
      },
      body: init?.body !== undefined ? JSON.stringify(init.body) : undefined,
      signal: trackerSignal(),
    });
  } catch {
    throw new Error("Could not reach GitHub. Try again in a moment.");
  }
  if (res.ok) return (await res.json()) as T;

  let detail = "";
  try {
    const body = (await res.json()) as { message?: string };
    detail = body.message ?? "";
  } catch {
    // ignore
  }
  if (res.status === 401) {
    throw new Error("GitHub did not accept this token. Create a fine-grained token with Issues read and write access.");
  }
  if (res.status === 403) {
    throw new Error(
      "This token cannot create issues in that repository. Give it Issues read and write access to the repository.",
    );
  }
  if (res.status === 404) throw new Error("GitHub could not find that repository, or the token cannot see it.");
  if (res.status === 410) {
    throw new Error("Issues are turned off for that repository. Turn them on in the repository settings.");
  }
  throw new Error(detail ? `GitHub returned an error: ${detail}` : `GitHub returned ${res.status}.`);
}

export async function verifyGitHubRepo(
  token: string,
  owner: string,
  repo: string,
): Promise<{ fullName: string; private: boolean }> {
  const data = await githubRequest<{ full_name: string; private: boolean; has_issues?: boolean }>(
    token,
    `/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repo)}`,
  );
  if (data.has_issues === false) {
    throw new Error("Issues are turned off for that repository. Turn them on in the repository settings.");
  }
  return { fullName: data.full_name, private: data.private };
}

const GITHUB_API_BODY_LIMIT = 60_000;

export async function createGitHubIssue(args: {
  token: string;
  owner: string;
  repo: string;
  title: string;
  body: string;
  labels?: string[];
}): Promise<{ number: number; url: string }> {
  const body =
    args.body.length > GITHUB_API_BODY_LIMIT ? `${args.body.slice(0, GITHUB_API_BODY_LIMIT)}\n\n_Truncated._` : args.body;
  const labels = (args.labels ?? []).map((l) => l.trim()).filter(Boolean);
  const data = await githubRequest<{ number: number; html_url: string }>(
    args.token,
    `/repos/${encodeURIComponent(args.owner)}/${encodeURIComponent(args.repo)}/issues`,
    { method: "POST", body: { title: args.title.slice(0, 250), body, ...(labels.length ? { labels } : {}) } },
  );
  return { number: data.number, url: data.html_url };
}
